-module(core).

%%% Поведение ядра системы уведомлений.
%%%
%%% Модуль ядра (например, alarm_manager) должен реализовать эти
%%% callback-функции, чтобы модули каналов могли фиксировать
%%% результаты доставки и подтверждения.

-export_type([reason/0]).

-type reason() :: term().

%%--------------------------------------------------------------------
%% Callback: mark_delivery/2
%%
%% Отмечает факт доставки уведомления абоненту.
%% Вызывается модулем канала после получения подтверждения доставки
%% (например, 200 OK на SIP MESSAGE).
%%--------------------------------------------------------------------
-callback mark_delivery(AlarmId :: alarm_db:alarm_id(),
                        ContactId :: sub_db:contact_id()) ->
    ok | {error, Reason :: reason()}.

%%--------------------------------------------------------------------
%% Callback: mark_confirmation/2
%%
%% Отмечает факт подтверждения получения уведомления пользователем
%% (например, встречный звонок на номер 4808).
%%
%% Если AlarmId равен атому undefined (канал не может определить,
%% к какому именно аларму относится подтверждение), реализация должна:
%%   - найти самый ранний (по времени создания) неподтверждённый
%%     аларм для подписчика, идентифицируемого ContactId;
%%   - отметить этот аларм как подтверждённый.
%%
%% Если для подписчика нет неподтверждённых алармов, возвращается
%% {error, no_pending_alarm}.
%%--------------------------------------------------------------------
-callback mark_confirmation(AlarmId :: alarm_db:alarm_id() | undefined,
                            ContactId :: sub_db:contact_id()) ->
    ok | {error, Reason :: reason()}.
